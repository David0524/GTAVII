"""Writes docs/PERIOD_AUDIT.md from docs/period_audit.csv and docs/period_audit_summary.json.
Run after build.ts (npm run data:audit). Pure stdlib; no network."""
import csv
import json
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
D = lambda *p: os.path.join(ROOT, *p)

rows = list(csv.DictReader(open(D('docs', 'period_audit.csv'))))
summ = json.load(open(D('docs', 'period_audit_summary.json')))
stats = json.load(open(D('public', 'data', 'world.json')))['stats']
s = summ['summary']


def table(filt, n=None):
    out = ['| Address | Name | PLUTO | Footprint | OSM | Height m | Decision | Why |', '|---|---|---|---|---|---|---|---|']
    sel = [r for r in rows if filt(r)]
    for r in (sel[:n] if n else sel):
        why = r['reason'].split(' (PLUTO')[0]
        out.append(f"| {r['address']} | {r['name']} | {r['pluto_year']} | {r['footprint_year']} | {r['osm_year']} | {r['height_m']} | {r['decision']} | {why} |")
    return '\n'.join(out)


removed_tall = [r for r in rows if r['decision'] == 'remove' and r['rule'] in ('2', '3', '5') and float(r['height_m']) >= 100]

doc = f"""# Period audit: is every building right for summer 1974?

Generated by `npm run data:build && npm run data:audit`. The full per-building table is
**[period_audit.csv](period_audit.csv)** (one row per footprint or tax lot in the play region,
tallest first). Counts are in [period_audit_summary.json](period_audit_summary.json). The dating
rules live in `tools/pipeline/dating.ts`, and the hand rulings in `PERIOD_OVERRIDES` in
`tools/pipeline/era1974.ts`.

## Method
Each building is dated from three independent sources:

| Source | Strength | Known failure |
|---|---|---|
| PLUTO `yearbuilt` (per tax lot) | Covers almost every lot | Lags when a new building replaces an old one on the same lot. Some years are estimates (1900, 1910, 1920...). |
| Footprint `construction_year` (per building) | Specific to the building | Sometimes stamped with a later alteration year |
| OSM `start_date` (matched by BIN) | Hand-curated, usually the original build | Sparse. Sometimes tagged on a whole complex or with a renovation year. |

**The rules, in order (the first match wins):**
- **0:** not a finished building (under construction, skybridge, marked for demolition) → removed.
- **1:** a reviewed manual override → as stated.
- **2:** OSM date ≤ 1974 → kept. OSM date > 1974 → removed.
- **2c:** the exception to the first half of rule 2. If PLUTO and the footprint agree on a year after 1974 and OSM is less than 15 years earlier, the gap is construction start vs completion, so the building is removed.
- **2b:** the exception to rule 2. If PLUTO and the footprint both say ≤ 1974, two sources agree, so the building is kept and the OSM date is read as a renovation.
- **3:** PLUTO or the footprint says > 1974 → removed.
- **3b:** the exception to rule 3. If only the footprint says > 1974 and the building keeps an original-series BIN (below 1076000), it's read as an alteration and kept. This only applies when the height is plausible for the era: up to 30 m before 1890, up to 80 m from 1890 to 1915.
- **4:** dated ≤ 1974 → kept.
- **5:** no date anywhere: kept as c.1920 if under 40 m, removed if 40 m or taller.

**Tax lots with no footprint at all:**
- **L1:** a pre-1975 building the footprint data is missing → modelled from the PLUTO lot.
- **L2:** a post-1974 tower too new for the footprint data, or vacant today → period stand-in.
- **L3:** a parking lot today → parking lot.
- **L0:** open space, or already covered by neighbours → left open.

**Why the rules lean toward removal.** A wrongly removed building becomes a plausible
period stand-in, which looks fine. A wrongly kept glass tower would break the setting.

## Results (play region)
- **Totals:** {s['footprintsInRegion']} footprints or lots were examined. **{s['kept']} were kept, {s['removed']} were
  removed and replaced by stand-ins or parking lots,** and {s['notBuildings']} records weren't
  finished buildings.
- **By rule:** {', '.join(f'{k}: {v}' for k, v in s['byRule'].items())}.
- **OSM building parts:** {stats.get('droppedModernParts', 0)} parts dated after 1974 were dropped from towers
  (later rooftop additions and crowns).
- **Distant skyline:** {s['skyline']['kept']} pre-1975 towers were kept and {s['skyline']['removed']} newer or undated ones
  removed. The Pan Am Building (1963) and the WTC twins were added by hand.

## Manual rulings (rule 1)
{table(lambda r: r['rule'] == '1')}

The Hotel Pennsylvania (1919, demolished 2022–23) is restored separately. See DATA_SOURCES.md.

## Flagged for human review
These are rows where the sources disagree and a rule decided. They're the best places to spend
research time.

{table(lambda r: r['flagged'] == 'yes')}

## Removed: the 40 tallest post-1974 buildings in the region
Sanity check: everything here should be a modern tower.

{table(lambda r: r in removed_tall, 40)}

## Distant skyline: kept towers over 200 m
{chr(10).join('- ' + x for x in summ['skylineKeptOver200m'])}

## Known limits
- **Rooftop additions.** Where a pre-1975 building gained floors later, today's roof height is
  used unless an override fixes it. Only 1107 Broadway is corrected so far. Rule-3b rows are
  the likeliest candidates.
- **Partial year coverage.** The data has years, not months, so a building dated 1974 is
  kept (e.g. 1166 Avenue of the Americas, completed 1974). Whether it was finished by summer
  isn't checked.
- **Hidden predecessors.** Some removed towers were built over older buildings that stood in
  1974, e.g. the Palace Theatre (1913) under the 1990 DoubleTree at 1568 Broadway. Restore
  these by override as they're researched.
- **Stand-in content.** Stand-ins are plausible period types, not the specific buildings that
  stood on each lot. Known predecessors can be added to `RESTORED_BUILDINGS` as research
  turns them up.
"""
open(D('docs', 'PERIOD_AUDIT.md'), 'w').write(doc)
print('wrote docs/PERIOD_AUDIT.md')
